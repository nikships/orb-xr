const val DEFAULT_ENVIRONMENT_ID = "black_void"

/**
 * A selectable immersive "focus mode" backdrop. [assetPath] is a `.glb`
 * *cubemap* (six inward-facing quads, one baked 4096² texture per face) under
 * the app's `assets/` folder, loaded as the spatial environment's *geometry*. A
 * null [assetPath] means the plain black void (no geometry).
 *
 * Why geometry and not an IBL skybox: the visible environment is
 * `SpatialEnvironmentPreference.geometry` (a `GltfModel`); the image-based
 * lighting slot only lights 3D objects, of which the terminal has none.
 *
 * Why a cubemap and not an equirect sky-dome: the original domes baked an 8K
 * panorama at only 2048×1024 onto a sphere — ~5.7 px/° at the horizon (about a
 * sixth of the Galaxy XR's ~32 px/°) and visibly stretched at the poles. The
 * cube resamples a Poly Haven 8K source into six 4096² faces (~35.7 px/° at
 * face centre), capturing the source with headroom and no pole pinch. Assets
 * are generated by `tools/build_environments.py`.
 */
data class TerminalEnvironment(
    val id: String,
    val label: String,
    val assetPath: String?,
)

val TERMINAL_ENVIRONMENTS: List<TerminalEnvironment> = listOf(
    TerminalEnvironment(DEFAULT_ENVIRONMENT_ID, "Black void", null),
    TerminalEnvironment("dikhololo_night", "Starry night", "environments/dikhololo_night.glb"),
    TerminalEnvironment("rogland_clear_night", "Clear night", "environments/rogland_clear_night.glb"),
    TerminalEnvironment("satara_night", "Dense stars", "environments/satara_night_no_lamps.glb"),
    TerminalEnvironment("moonless_golf", "Moonless", "environments/moonless_golf.glb"),
)

fun environmentForId(id: String): TerminalEnvironment =
    TERMINAL_ENVIRONMENTS.firstOrNull { it.id == id } ?: TERMINAL_ENVIRONMENTS.first()

/**
 * Apply the immersive focus-mode environment to the live XR session.
 *
 * When [immersive] is off we hand passthrough/environment control back to the
 * system. When on, we set the selected [environment]'s geometry (loading and
 * caching its `.glb` lazily) and drop passthrough opacity to 0 so the dome is
 * all the user sees. Both are *preferences* that only take effect while the
 * matching capability is live — callers gate on that. No-op without a session
 * (phone / 2D preview).
 *
 * @param modelCache reused across calls so re-selecting an environment doesn't
 *                   reload its glb; survives toggling immersive on/off.
 */
suspend fun applyImmersiveEnvironment(
    session: Session?,
    immersive: Boolean,
    environment: TerminalEnvironment,
    modelCache: MutableMap<String, GltfModel>,
) {
    val spatialEnvironment = session?.scene?.spatialEnvironment ?: return
    if (!immersive) {
        spatialEnvironment.preferredPassthroughOpacity = 1f
        spatialEnvironment.preferredSpatialEnvironment = null
        return
    }

    val geometry: GltfModel? = environment.assetPath?.let { path ->
        // The Uri overload accepts the same asset-relative path without requiring
        // java.nio.file.Paths, which is unavailable on API 24 and 25.
        modelCache[environment.id] ?: GltfModel.create(session, Uri.parse(path)).also {
            modelCache[environment.id] = it
        }
    }
    // Null geometry → black void (per Jetpack XR docs); a loaded dome → that
    // panorama. Revealed once passthrough opacity drops to 0.
    spatialEnvironment.preferredSpatialEnvironment =
        SpatialEnvironment.SpatialEnvironmentPreference(
            null as ImageBasedLightingAsset?,
            geometry,
        )
    spatialEnvironment.preferredPassthroughOpacity = 0f
}

/** Settings sub-section: pick which backdrop immersive focus mode shows. */
@Composable
fun EnvironmentPicker(
    selectedId: String,
    onSelected: (String) -> Unit,
    modifier: Modifier = Modifier,
) {
    Column(modifier = modifier, verticalArrangement = Arrangement.spacedBy(6.dp)) {
        GxrText("Environment", fontSize = 12.sp, color = GhosttyTokens.Accent)
        TERMINAL_ENVIRONMENTS.forEach { environment ->
            GxrChip(
                modifier = Modifier.fillMaxWidth(),
                label = environment.label,
                selected = environment.id == selectedId,
                onClick = { onSelected(environment.id) },
            )
        }
    }
}
